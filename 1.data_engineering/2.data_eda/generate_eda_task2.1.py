def load_data(input_path: Path):
    df = pd.read_csv(input_path)
    if 'date' not in df.columns or 'daily_qty' not in df.columns:
        raise ValueError('Input CSV must contain at least date and daily_qty columns.')

    df['date'] = pd.to_datetime(df['date'])
    df['daily_qty'] = pd.to_numeric(df['daily_qty'], errors='raise')

    if 'weekday' not in df.columns:
        df['weekday'] = df['date'].dt.day_name()
    if 'is_weekend' not in df.columns:
        df['is_weekend'] = df['weekday'].isin(['Saturday', 'Sunday'])
    if 'month' not in df.columns:
        df['month'] = df['date'].dt.month
    if 'season' not in df.columns:
        def season_from_month(m):
            if m in [12, 1, 2]:
                return 'Winter'
            if m in [3, 4, 5]:
                return 'Spring'
            if m in [6, 7, 8]:
                return 'Summer'
            return 'Autumn'
        df['season'] = df['month'].map(season_from_month)

    df['weekday'] = pd.Categorical(df['weekday'], categories=WEEKDAY_ORDER, ordered=True)
    df['month'] = pd.Categorical(df['month'], categories=MONTH_ORDER, ordered=True)
    df = df.sort_values('date').reset_index(drop=True)
    return df


def detect_outliers(df):
    q1 = df['daily_qty'].quantile(0.25)
    q3 = df['daily_qty'].quantile(0.75)
    iqr = q3 - q1
    lower = q1 - 1.5 * iqr
    upper = q3 + 1.5 * iqr
    return df[(df['daily_qty'] < lower) | (df['daily_qty'] > upper)].copy()


def write_eda_summary(df, outliers):
    full_range = pd.date_range(start=df['date'].min(), end=df['date'].max(), freq='D')
    missing_dates = int(len(full_range.difference(df['date'])))
    summary = {
        'metric': [
            'start_date',
            'end_date',
            'number_of_days',
            'missing_dates',
            'count',
            'mean',
            'median',
            'std',
            'min',
            'max',
            'iqr_outlier_count',
        ],
        'value': [
            df['date'].min().strftime('%Y-%m-%d'),
            df['date'].max().strftime('%Y-%m-%d'),
            len(df),
            missing_dates,
            len(df),
            round(float(df['daily_qty'].mean()), 2),
            round(float(df['daily_qty'].median()), 2),
            round(float(df['daily_qty'].std()), 2),
            round(float(df['daily_qty'].min()), 2),
            round(float(df['daily_qty'].max()), 2),
            len(outliers),
        ],
    }
    out = pd.DataFrame(summary)
    out.to_csv(TABLE_DIR / '01_eda_summary.csv', index=False)
    return out


def write_weekday_summary(df):
    s = (
        df.groupby('weekday', observed=False)['daily_qty']
        .agg(['count', 'mean', 'median', 'std'])
        .reindex(WEEKDAY_ORDER)
        .reset_index()
        .rename(columns={'weekday': 'weekday', 'count': 'count', 'mean': 'mean', 'median': 'median', 'std': 'std'})
    )
    s['mean'] = s['mean'].round(2)
    s['median'] = s['median'].round(2)
    s['std'] = s['std'].round(2)
    s.to_csv(TABLE_DIR / '02_weekday_summary.csv', index=False)
    return s


def write_month_summary(df):
    s = (
        df.groupby('month', observed=False)['daily_qty']
        .agg(['count', 'mean', 'median', 'std'])
        .reindex(MONTH_ORDER)
        .reset_index()
        .rename(columns={'month': 'month', 'count': 'count', 'mean': 'mean', 'median': 'median', 'std': 'std'})
    )
    s['mean'] = s['mean'].round(2)
    s['median'] = s['median'].round(2)
    s['std'] = s['std'].round(2)
    s.to_csv(TABLE_DIR / '03_month_summary.csv', index=False)
    return s


def write_outlier_days(outliers):
    out = outliers[['date', 'daily_qty', 'weekday', 'month', 'is_weekend']].copy()
    out['date'] = out['date'].dt.strftime('%Y-%m-%d')
    out['daily_qty'] = out['daily_qty'].round(2)
    out.to_csv(TABLE_DIR / '04_outlier_days.csv', index=False)
    return out


def figure_daily_demand_trend(df, outliers):
    configure_style()
    fig, ax = plt.subplots(figsize=(12, 5.5))
    rolling = df['daily_qty'].rolling(window=30, min_periods=1).mean()
    ax.plot(df['date'], df['daily_qty'], color='#B0B0B0', linewidth=1.1, alpha=0.9, label='Daily observations')
    ax.plot(df['date'], rolling, color='#1F3552', linewidth=2.4, label='30-day rolling mean')
    if not outliers.empty:
        ax.scatter(outliers['date'], outliers['daily_qty'], color='#E69F00', s=22, zorder=3, label='IQR outliers')
        top = outliers.nlargest(5, 'daily_qty')
        for _, r in top.iterrows():
            ax.annotate(
                r['date'].strftime('%Y-%m-%d'),
                (r['date'], r['daily_qty']),
                xytext=(6, 8),
                textcoords='offset points',
                fontsize=7.5,
                color='#1F3552',
                ha='left',
                va='bottom',
            )
    ax.set_title('Daily Demand Over Time', pad=8)
    ax.set_xlabel('Date')
    ax.set_ylabel('daily_qty')
    ax.legend(frameon=False, loc='upper left', fontsize=9)
    ax.xaxis.set_major_locator(mdates.YearLocator(base=1))
    ax.xaxis.set_major_formatter(mdates.DateFormatter('%Y'))
    ax.margins(x=0.01)
    fig.autofmt_xdate(rotation=0)
    fig.tight_layout()
    fig.savefig(FIG_DIR / '01_daily_demand_trend.png', bbox_inches='tight')
    plt.close(fig)


def figure_weekday_distribution(df):
    configure_style()
    fig, ax = plt.subplots(figsize=(10, 5.5))
    data = [df.loc[df['weekday'] == wd, 'daily_qty'].values for wd in WEEKDAY_ORDER]
    ax.boxplot(
        data,
        patch_artist=True,
        widths=0.55,
        tick_labels=WEEKDAY_ORDER,
        boxprops=dict(facecolor='#D9EAF7', edgecolor='#1F3552', linewidth=1.2),
        medianprops=dict(color='#1F3552', linewidth=1.8),
        whiskerprops=dict(color='#5A5A5A', linewidth=1.0),
        capprops=dict(color='#5A5A5A', linewidth=1.0),
    )
    means = df.groupby('weekday', observed=False)['daily_qty'].mean().reindex(WEEKDAY_ORDER)
    for i, value in enumerate(means.values, start=1):
        ax.scatter(i, value, color='#E69F00', s=28, marker='D', zorder=3)
    ax.set_title('Daily Demand Distribution by Weekday', pad=8)
    ax.set_xlabel('Weekday')
    ax.set_ylabel('daily_qty')
    ax.set_ylim(0, max(df['daily_qty'].max() * 1.15, 15000))
    fig.tight_layout()
    fig.savefig(FIG_DIR / '02_weekday_demand_distribution.png', bbox_inches='tight')
    plt.close(fig)


