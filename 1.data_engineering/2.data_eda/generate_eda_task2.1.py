def figure_daily_distribution(df):
    configure_style()
    fig, ax = plt.subplots(figsize=(10, 5.5))
    ax.hist(df['daily_qty'], bins=30, color='#D9EAF7', edgecolor='#1F3552', linewidth=0.9, alpha=0.9)
    mean_val = df['daily_qty'].mean()
    median_val = df['daily_qty'].median()
    ax.axvline(mean_val, color='#1F3552', linestyle='--', linewidth=1.8, label=f'Mean = {mean_val:,.0f}')
    ax.axvline(median_val, color='#E69F00', linestyle='-.', linewidth=1.8, label=f'Median = {median_val:,.0f}')
    ax.set_title('Distribution of Daily Demand', pad=8)
    ax.set_xlabel('daily_qty')
    ax.set_ylabel('Number of days')
    ax.legend(frameon=False, loc='upper right', fontsize=9)
    fig.tight_layout()
    fig.savefig(FIG_DIR / '04_daily_demand_distribution.png', bbox_inches='tight')
    plt.close(fig)


